package main

import (
	"bytes"
	"cmp"
	"encoding"
	"encoding/json"
	"fmt"
	"maps"
	"math"
	"reflect"
	"regexp"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/xaroth/dashboard/module"
)

var (
	timeType          = reflect.TypeFor[time.Time]()
	durationType      = reflect.TypeFor[module.Duration]()
	rawMessageType    = reflect.TypeFor[json.RawMessage]()
	jsonMarshaler     = reflect.TypeFor[json.Marshaler]()
	textMarshaler     = reflect.TypeFor[encoding.TextMarshaler]()
	identifier        = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
	nonIdentifierRune = regexp.MustCompile(`[^A-Za-z0-9_$]`)
)

type declKey struct {
	t        reflect.Type
	optional bool
}

// generator collects named TypeScript interfaces while walking Go types.
type generator struct {
	names map[declKey]string
	decls map[string]string
	// prefix names the module whose types are being walked.
	prefix string
}

func generate(regs []module.Registration) ([]byte, error) {
	regs = slices.SortedFunc(slices.Values(regs), func(a, b module.Registration) int { return cmp.Compare(a.Name(), b.Name()) })
	g := &generator{names: map[declKey]string{}, decls: map[string]string{}}
	var entries []string
	for _, r := range regs {
		g.prefix = pascal(r.Name())
		for _, q := range r.QueryTypes() {
			params, err := g.params(q.Params, g.prefix+pascal(q.Name)+"Params")
			if err != nil {
				return nil, fmt.Errorf("%s.%s params: %w", r.Name(), q.Name, err)
			}
			result, err := g.typeOf(q.Result, g.prefix+pascal(q.Name)+"Result")
			if err != nil {
				return nil, fmt.Errorf("%s.%s result: %w", r.Name(), q.Name, err)
			}
			entries = append(entries, fmt.Sprintf("  %q: { params: %s; result: %s };", r.Name()+"."+q.Name, params, result))
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gentypes. DO NOT EDIT.\n\n")
	b.WriteString("/** A Go duration string, e.g. \"24h\" or \"1h30m\". */\nexport type Duration = string;\n")
	for _, name := range slices.Sorted(maps.Keys(g.decls)) {
		b.WriteString("\n" + g.decls[name])
	}
	b.WriteString("\n/** Every query: \"module.query\" to its params and result. */\nexport interface Queries {\n")
	for _, e := range entries {
		b.WriteString(e + "\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// params declares the params struct with every field optional: a missing
// param is the Go zero value, which queries treat as their default.
func (g *generator) params(t reflect.Type, name string) (string, error) {
	if t.Kind() != reflect.Struct {
		return "", fmt.Errorf("params must be a struct, got %s", t)
	}
	if t.NumField() == 0 {
		return "Record<string, never>", nil
	}
	return g.declare(t, name, true)
}

// typeOf returns the TypeScript type for t; named structs become interfaces.
func (g *generator) typeOf(t reflect.Type, hint string) (string, error) {
	switch {
	case t == timeType:
		return "string", nil
	case t == durationType:
		return "Duration", nil
	case t == rawMessageType:
		return "unknown", nil
	case implements(t, jsonMarshaler) || implements(t, textMarshaler):
		// Its JSON is whatever the method writes; the kind says nothing.
		return "", fmt.Errorf("%s has its own JSON encoding; add it to gentypes", t)
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner, err := g.typeOf(t.Elem(), hint)
		return inner + " | null", err
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Slice, reflect.Array:
		if t.Kind() == reflect.Slice && t.Elem().Kind() == reflect.Uint8 {
			return "string", nil // encoding/json writes bytes as base64
		}
		// Typed as arrays, not T[] | null: queries return non-nil slices.
		inner, err := g.typeOf(t.Elem(), hint)
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map keys must be strings, got %s", t)
		}
		inner, err := g.typeOf(t.Elem(), hint)
		return "Record<string, " + inner + ">", err
	case reflect.Struct:
		name := hint
		if t.Name() != "" {
			// Generic instantiations are named like Page[int]; keep the identifier characters.
			name = g.prefix + pascal(nonIdentifierRune.ReplaceAllString(t.Name(), "_"))
		}
		return g.declare(t, name, false)
	case reflect.Interface:
		return "unknown", nil
	}
	return "", fmt.Errorf("unsupported type %s", t)
}

// declare emits an interface for struct t once per use (params fields are
// optional, results are not) and returns its name.
func (g *generator) declare(t reflect.Type, name string, optional bool) (string, error) {
	key := declKey{t, optional}
	if n, ok := g.names[key]; ok {
		return n, nil
	}
	if _, taken := g.decls[name]; taken {
		return "", fmt.Errorf("two types map to %s", name)
	}
	g.names[key] = name
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", name)
	if err := g.fields(&b, t, optional); err != nil {
		return "", err
	}
	b.WriteString("}\n")
	g.decls[name] = b.String()
	return name, nil
}

func (g *generator) fields(b *strings.Builder, t reflect.Type, optional bool) error {
	for _, f := range jsonFields(t) {
		ts, err := g.typeOf(f.typ, g.prefix+pascal(f.goName))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", t, f.goName, err)
		}
		omit := f.has("omitempty") || f.has("omitzero")
		if omit && f.typ.Kind() == reflect.Pointer {
			// Omitted when nil, so never null when present.
			ts = strings.TrimSuffix(ts, " | null")
		}
		if f.has("string") {
			switch f.typ.Kind() {
			case reflect.Bool, reflect.String,
				reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
				reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
				reflect.Float32, reflect.Float64:
				ts = "string"
			}
		}
		mark := ""
		if optional || omit {
			mark = "?"
		}
		name := f.name
		if !identifier.MatchString(name) {
			name = fmt.Sprintf("%q", name)
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, mark, ts)
	}
	return nil
}

type jsonField struct {
	name   string
	goName string
	typ    reflect.Type
	opts   string
	tagged bool
	depth  int
}

func (f jsonField) has(opt string) bool {
	return slices.Contains(strings.Split(f.opts, ","), opt)
}

// jsonFields lists the fields encoding/json writes for struct t, in its
// order: embedded structs (also pointer and unexported ones) are flattened,
// and of several fields with one name the shallowest wins, a tagged one
// breaks a tie, and an unbroken tie drops them all.
func jsonFields(t reflect.Type) []jsonField {
	var all []jsonField
	var walk func(t reflect.Type, depth int, seen map[reflect.Type]bool)
	walk = func(t reflect.Type, depth int, seen map[reflect.Type]bool) {
		if seen[t] {
			return
		}
		seen = maps.Clone(seen)
		seen[t] = true
		for i := range t.NumField() {
			f := t.Field(i)
			tag := f.Tag.Get("json")
			if tag == "-" {
				continue
			}
			name, opts, _ := strings.Cut(tag, ",")
			ft := f.Type
			if f.Anonymous {
				if ft.Kind() == reflect.Pointer {
					ft = ft.Elem()
				}
				if name == "" && ft.Kind() == reflect.Struct {
					walk(ft, depth+1, seen)
					continue
				}
				if !f.IsExported() {
					continue
				}
			} else if !f.IsExported() {
				continue
			}
			all = append(all, jsonField{name: cmp.Or(name, f.Name), goName: f.Name, typ: f.Type, opts: opts, tagged: name != "", depth: depth})
		}
	}
	walk(t, 0, map[reflect.Type]bool{})

	byName := map[string][]int{}
	for i, f := range all {
		byName[f.name] = append(byName[f.name], i)
	}
	keep := map[int]bool{}
	for _, idx := range byName {
		if i, ok := dominant(all, idx); ok {
			keep[i] = true
		}
	}
	var out []jsonField
	for i, f := range all {
		if keep[i] {
			out = append(out, f)
		}
	}
	return out
}

// dominant picks the field encoding/json writes among those sharing a name.
func dominant(all []jsonField, idx []int) (int, bool) {
	depth := math.MaxInt
	for _, i := range idx {
		depth = min(depth, all[i].depth)
	}
	var shallow, tagged []int
	for _, i := range idx {
		if all[i].depth == depth {
			shallow = append(shallow, i)
			if all[i].tagged {
				tagged = append(tagged, i)
			}
		}
	}
	switch {
	case len(shallow) == 1:
		return shallow[0], true
	case len(tagged) == 1:
		return tagged[0], true
	}
	return 0, false
}

func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

func implements(t, iface reflect.Type) bool {
	return t.Implements(iface) || reflect.PointerTo(t).Implements(iface)
}
