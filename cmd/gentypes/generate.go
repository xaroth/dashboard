package main

import (
	"bytes"
	"cmp"
	"fmt"
	"maps"
	"reflect"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/xaroth/dashboard/service/modules"
)

var (
	timeType     = reflect.TypeFor[time.Time]()
	durationType = reflect.TypeFor[modules.Duration]()
)

// generator collects named TypeScript interfaces while walking Go types.
type generator struct {
	names map[reflect.Type]string
	decls map[string]string
	// prefix names the module whose types are being walked.
	prefix string
}

func generate(regs []modules.Registration) ([]byte, error) {
	regs = slices.SortedFunc(slices.Values(regs), func(a, b modules.Registration) int { return cmp.Compare(a.Name(), b.Name()) })
	g := &generator{names: map[reflect.Type]string{}, decls: map[string]string{}}
	var entries []string
	for _, r := range regs {
		g.prefix = pascal(r.Name())
		for _, q := range r.QueryTypes() {
			params, err := g.params(q.Params, g.prefix+pascal(q.Name)+"Params")
			if err != nil {
				return nil, fmt.Errorf("%s.%s params: %w", r.Name(), q.Name, err)
			}
			result, err := g.typeOf(q.Result, g.prefix+pascal(q.Name)+"Result")
			if err != nil {
				return nil, fmt.Errorf("%s.%s result: %w", r.Name(), q.Name, err)
			}
			entries = append(entries, fmt.Sprintf("  %q: { params: %s; result: %s };", r.Name()+"."+q.Name, params, result))
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gentypes. DO NOT EDIT.\n\n")
	b.WriteString("/** A Go duration string, e.g. \"24h\" or \"1h30m\". */\nexport type Duration = string;\n")
	for _, name := range slices.Sorted(maps.Keys(g.decls)) {
		b.WriteString("\n" + g.decls[name])
	}
	b.WriteString("\n/** Every query: \"module.query\" to its params and result. */\nexport interface Queries {\n")
	for _, e := range entries {
		b.WriteString(e + "\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// params declares the params struct with every field optional: a missing
// param is the Go zero value, which queries treat as their default.
func (g *generator) params(t reflect.Type, name string) (string, error) {
	if t.Kind() != reflect.Struct {
		return "", fmt.Errorf("params must be a struct, got %s", t)
	}
	if t.NumField() == 0 {
		return "Record<string, never>", nil
	}
	return g.declare(t, name, true)
}

// typeOf returns the TypeScript type for t; named structs become interfaces.
func (g *generator) typeOf(t reflect.Type, hint string) (string, error) {
	switch {
	case t == timeType:
		return "string", nil
	case t == durationType:
		return "Duration", nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		inner, err := g.typeOf(t.Elem(), hint)
		return inner + " | null", err
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Slice, reflect.Array:
		if t.Elem().Kind() == reflect.Uint8 {
			return "string", nil // encoding/json writes bytes as base64
		}
		// Typed as arrays, not T[] | null: queries return non-nil slices.
		inner, err := g.typeOf(t.Elem(), hint)
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", err
	case reflect.Map:
		if t.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map keys must be strings, got %s", t)
		}
		inner, err := g.typeOf(t.Elem(), hint)
		return "Record<string, " + inner + ">", err
	case reflect.Struct:
		name := hint
		if t.Name() != "" {
			name = g.prefix + pascal(t.Name())
		}
		return g.declare(t, name, false)
	case reflect.Interface:
		return "unknown", nil
	}
	return "", fmt.Errorf("unsupported type %s", t)
}

// declare emits an interface for struct t once and returns its name.
func (g *generator) declare(t reflect.Type, name string, optional bool) (string, error) {
	if n, ok := g.names[t]; ok {
		return n, nil
	}
	if _, taken := g.decls[name]; taken {
		return "", fmt.Errorf("two types map to %s", name)
	}
	g.names[t] = name
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", name)
	if err := g.fields(&b, t, optional); err != nil {
		return "", err
	}
	b.WriteString("}\n")
	g.decls[name] = b.String()
	return name, nil
}

func (g *generator) fields(b *strings.Builder, t reflect.Type, optional bool) error {
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" && f.Type.Kind() == reflect.Struct {
			if err := g.fields(b, f.Type, optional); err != nil {
				return err
			}
			continue
		}
		if name == "" {
			name = f.Name
		}
		ts, err := g.typeOf(f.Type, g.prefix+pascal(f.Name))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", t, f.Name, err)
		}
		mark := ""
		if optional || strings.Contains(opts, "omitempty") || strings.Contains(opts, "omitzero") {
			mark = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, mark, ts)
	}
	return nil
}

func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}
