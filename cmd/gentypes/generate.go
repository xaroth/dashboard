package main

import (
	"bytes"
	"cmp"
	"encoding"
	"encoding/json"
	"fmt"
	"maps"
	"reflect"
	"regexp"
	"slices"
	"strings"
	"time"
	"unicode"

	"github.com/xaroth/dashboard/module"
)

var (
	timeType          = reflect.TypeFor[time.Time]()
	jsonMarshaler     = reflect.TypeFor[json.Marshaler]()
	textMarshaler     = reflect.TypeFor[encoding.TextMarshaler]()
	identifier        = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
	nonIdentifierRune = regexp.MustCompile(`[^A-Za-z0-9_$]`)
)

type declKey struct {
	t        reflect.Type
	optional bool
}

// generator collects named TypeScript interfaces while walking Go types.
type generator struct {
	names map[declKey]string
	decls map[string]string
	// prefix names the module whose types are being walked.
	prefix string
}

func generate(regs []module.Registration) ([]byte, error) {
	regs = slices.SortedFunc(slices.Values(regs), func(a, b module.Registration) int { return cmp.Compare(a.Name(), b.Name()) })
	g := &generator{names: map[declKey]string{}, decls: map[string]string{}}
	var entries []string
	for _, r := range regs {
		g.prefix = pascal(r.Name())
		for _, q := range r.QueryTypes() {
			params, err := g.params(q.Params, g.prefix+pascal(q.Name)+"Params")
			if err != nil {
				return nil, fmt.Errorf("%s.%s params: %w", r.Name(), q.Name, err)
			}
			result, err := g.typeOf(q.Result, g.prefix+pascal(q.Name)+"Result")
			if err != nil {
				return nil, fmt.Errorf("%s.%s result: %w", r.Name(), q.Name, err)
			}
			entries = append(entries, fmt.Sprintf("  %q: { params: %s; result: %s };", r.Name()+"."+q.Name, params, result))
		}
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gentypes. DO NOT EDIT.\n")
	for _, name := range slices.Sorted(maps.Keys(g.decls)) {
		b.WriteString("\n" + g.decls[name])
	}
	b.WriteString("\n/** Every query: \"module.query\" to its params and result. */\nexport interface Queries {\n")
	for _, e := range entries {
		b.WriteString(e + "\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// params declares the params struct with every field optional: a missing
// param is the Go zero value, which queries treat as their default.
func (g *generator) params(t reflect.Type, name string) (string, error) {
	if t.Kind() != reflect.Struct {
		return "", fmt.Errorf("params must be a struct, got %s", t)
	}
	if t.NumField() == 0 {
		return "Record<string, never>", nil
	}
	return g.declare(t, name, true)
}

// typeOf returns the TypeScript type for t; named structs become interfaces.
// Types the pages do not use yet are errors rather than guesses.
func (g *generator) typeOf(t reflect.Type, hint string) (string, error) {
	switch {
	case t == timeType:
		return "string", nil
	case t.Kind() == reflect.Pointer:
		// Checked before the marshalers: *T has the methods of T.
		inner, err := g.typeOf(t.Elem(), hint)
		return inner + " | null", err
	case implements(t, jsonMarshaler) || implements(t, textMarshaler):
		// Its JSON is whatever the method writes; the kind says nothing.
		return "", fmt.Errorf("%s has its own JSON encoding; add it to gentypes", t)
	}
	switch t.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Slice:
		if t.Elem().Kind() == reflect.Uint8 {
			return "", fmt.Errorf("unsupported type %s", t)
		}
		// Typed as arrays, not T[] | null: queries return non-nil slices.
		inner, err := g.typeOf(t.Elem(), hint)
		if strings.Contains(inner, "|") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", err
	case reflect.Struct:
		name := hint
		if t.Name() != "" {
			// Generic instantiations are named like Page[int]; keep the identifier characters.
			name = g.prefix + pascal(nonIdentifierRune.ReplaceAllString(t.Name(), "_"))
		}
		return g.declare(t, name, false)
	}
	return "", fmt.Errorf("unsupported type %s", t)
}

// declare emits an interface for struct t once per use (params fields are
// optional, results are not) and returns its name.
func (g *generator) declare(t reflect.Type, name string, optional bool) (string, error) {
	key := declKey{t, optional}
	if n, ok := g.names[key]; ok {
		return n, nil
	}
	if _, taken := g.decls[name]; taken {
		return "", fmt.Errorf("two types map to %s", name)
	}
	g.names[key] = name
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", name)
	if err := g.fields(&b, t, optional); err != nil {
		return "", err
	}
	b.WriteString("}\n")
	g.decls[name] = b.String()
	return name, nil
}

// fields writes the exported fields of t as encoding/json names them.
func (g *generator) fields(b *strings.Builder, t reflect.Type, optional bool) error {
	for f := range t.Fields() {
		tag := f.Tag.Get("json")
		if !f.IsExported() && !f.Anonymous || tag == "-" {
			continue
		}
		if f.Anonymous {
			return fmt.Errorf("%s.%s: embedded fields are not supported", t, f.Name)
		}
		name, opts, _ := strings.Cut(tag, ",")
		name = cmp.Or(name, f.Name)
		var omit bool
		for opt := range strings.SplitSeq(opts, ",") {
			switch opt {
			case "":
			case "omitempty", "omitzero":
				omit = true
			default:
				return fmt.Errorf("%s.%s: json option %q is not supported", t, f.Name, opt)
			}
		}
		ts, err := g.typeOf(f.Type, g.prefix+pascal(f.Name))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", t, f.Name, err)
		}
		if omit && f.Type.Kind() == reflect.Pointer {
			// Omitted when nil, so never null when present.
			ts = strings.TrimSuffix(ts, " | null")
		}
		mark := ""
		if optional || omit {
			mark = "?"
		}
		if !identifier.MatchString(name) {
			name = fmt.Sprintf("%q", name)
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, mark, ts)
	}
	return nil
}

func pascal(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '_' {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

func implements(t, iface reflect.Type) bool {
	return t.Implements(iface) || reflect.PointerTo(t).Implements(iface)
}
